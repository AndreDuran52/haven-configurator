// Bake the top-down outline of Andre's square pillow (src/three/models/
// pillow-square.glb) for the plan (Andre, 2026-11-09: plan pillows match the
// 3D Top exactly). Does what the 3D does to the model (src/three/models.ts):
// the node's transform, squareUp (a quarter turn when the model is wider in z
// than in x), fitToBox onto SQUARE_PILLOW (w × h × t), then the lean back
// (boxTransform's Rx(−lean)); then looks straight down and keeps the convex
// hull, in pillow inches: [across, forward] (forward = the way it faces).
// Run after changing the model or SQUARE_PILLOW:
//   node scripts/pillow-outline.mjs > src/plan/pillowOutline.ts
import { readFileSync } from 'node:fs'

const MODEL = new URL('../src/three/models/pillow-square.glb', import.meta.url)
const SRC = readFileSync(new URL('../src/engine/pillows.ts', import.meta.url), 'utf8')
const m = /SQUARE_PILLOW = \{ w: ([\d.]+), h: ([\d.]+), t: ([\d.]+), lean: ([\d.]+) \}/.exec(SRC)
if (!m) throw new Error('SQUARE_PILLOW not found in src/engine/pillows.ts')
const [W, H, T, LEAN] = m.slice(1).map(Number)

// glTF binary: header, JSON chunk, BIN chunk.
const buf = readFileSync(MODEL)
const jsonLen = buf.readUInt32LE(12)
const json = JSON.parse(buf.subarray(20, 20 + jsonLen).toString())
const bin = 20 + jsonLen + 8

const rotate = ([x, y, z], [qx, qy, qz, qw]) => {
  // v' = q v q*
  const ix = qw * x + qy * z - qz * y
  const iy = qw * y + qz * x - qx * z
  const iz = qw * z + qx * y - qy * x
  const iw = -qx * x - qy * y - qz * z
  return [ix * qw + iw * -qx + iy * -qz - iz * -qy, iy * qw + iw * -qy + iz * -qx - ix * -qz, iz * qw + iw * -qz + ix * -qy - iy * -qx]
}

const pts = []
for (const node of json.nodes) {
  if (node.mesh === undefined) continue
  const s = node.scale ?? [1, 1, 1]
  const q = node.rotation ?? [0, 0, 0, 1]
  for (const prim of json.meshes[node.mesh].primitives) {
    const acc = json.accessors[prim.attributes.POSITION]
    const view = json.bufferViews[acc.bufferView]
    const off = bin + (view.byteOffset ?? 0) + (acc.byteOffset ?? 0)
    const stride = view.byteStride ?? 12
    for (let i = 0; i < acc.count; i++) {
      const p = [0, 1, 2].map((k) => buf.readFloatLE(off + i * stride + k * 4) * s[k])
      pts.push(rotate(p, q))
    }
  }
}

// squareUp: geometry.rotateY(π/2) when the x extent is the smaller: (x, y, z) -> (z, y, −x).
const ext = (list, k) => Math.max(...list.map((p) => p[k])) - Math.min(...list.map((p) => p[k]))
const up = ext(pts, 0) < ext(pts, 2) ? pts.map(([x, y, z]) => [z, y, -x]) : pts
// fitToBox: centre on the bounds, scale each axis onto W × H × T.
const lo = [0, 1, 2].map((k) => Math.min(...up.map((p) => p[k])))
const hi = [0, 1, 2].map((k) => Math.max(...up.map((p) => p[k])))
const size = [W, H, T]
const fit = up.map((p) => p.map((v, k) => ((v - (lo[k] + hi[k]) / 2) * size[k]) / (hi[k] - lo[k])))
// The lean: Rx(−lean), the top going back; then seen from above: (x, z).
const a = (-LEAN * Math.PI) / 180
const flat = fit.map(([x, y, z]) => [x, y * Math.sin(a) + z * Math.cos(a)])

// Convex hull (monotone chain), rounded to 0.01″.
const r2 = (v) => Math.round(v * 100) / 100 + 0
const uniq = [...new Map(flat.map(([x, y]) => [`${r2(x)},${r2(y)}`, [r2(x), r2(y)]])).values()].sort((p, q) => p[0] - q[0] || p[1] - q[1])
const cross = (o, p, q) => (p[0] - o[0]) * (q[1] - o[1]) - (p[1] - o[1]) * (q[0] - o[0])
const half = (list) => {
  const out = []
  for (const p of list) {
    while (out.length >= 2 && cross(out[out.length - 2], out[out.length - 1], p) <= 0) out.pop()
    out.push(p)
  }
  out.pop()
  return out
}
const hull = [...half(uniq), ...half([...uniq].reverse())]

console.log(`// Generated by scripts/pillow-outline.mjs from src/three/models/pillow-square.glb
// (SQUARE_PILLOW ${W} × ${H} × ${T}″, leaning ${LEAN}°). Do not edit: re-run the script.
// The square pillow seen from above, as the 3D draws it: its convex outline in
// pillow inches, [across, forward] (forward = the way it faces), about its box centre.
export const PILLOW_OUTLINE: readonly (readonly [number, number])[] = [
${hull.map(([x, y]) => `  [${x}, ${y}],`).join('\n')}
];`)
